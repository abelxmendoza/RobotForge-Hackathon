#!/usr/bin/env python3
"""Build catalog/parts-kits.json — the take-apart parts kit of every
Robodex entry, generated by the repo's own CAD kit generator
(src/robotforge/cad.py) from the entry's spec file.

For each robot in catalog/robots.json this runs cad.generate_kit() on
the robot's spec and records, per part: the generator's own name,
file, quantity, plain-language "does" line, dimensions line and print
note, plus the named parameters the generated OpenSCAD file exposes
(name, current value in mm, and the source comment the generator
prints next to it — "from spec ...", "derived — ..." or
"assumption — ...").

A spec the kit generator cannot build a kit for (today: any spec with
no wheels — the kit covers wheeled ground robots) is recorded as
kit: null with the reason, so the site can say honestly that no kit
is defined for that entry instead of inventing parts.

Deterministic: cad.generate_kit is byte-deterministic and this script
sorts nothing the generator did not already order.

    python3 tools/build_parts_kits.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from robotforge import cad  # noqa: E402
from robotforge.schema import RobotSpec  # noqa: E402

PARAM_RE = re.compile(r"^([a-z][a-z_0-9]*) = ([-\d.]+);\s+// (.*)$", re.M)


def slug_of(name: str) -> str:
    """Mirror of web-next robotSlug(): name-derived URL slug."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def kit_for(spec: RobotSpec) -> dict:
    files = cad.generate_kit(spec)
    parts = []
    for info in cad.part_infos(spec):
        text = files[info.filename]
        params = [
            {"name": name, "value_mm": float(value), "source": source}
            for name, value, source in PARAM_RE.findall(text)
        ]
        parts.append({
            "name": info.name,
            "file": info.filename,
            "qty": info.qty,
            "does": info.does,
            "dims": info.dims,
            "print_note": info.print_note,
            "params": params,
        })
    return {"estimated": cad.is_estimated(spec), "parts": parts}


def main() -> int:
    robots = json.loads((REPO / "catalog" / "robots.json").read_text())
    kits: dict[str, dict] = {}
    for robot in robots["robots"]:
        slug = slug_of(robot["name"])
        spec_file = robot.get("spec_file")
        entry: dict = {"robot": robot["name"], "spec_file": spec_file}
        if not spec_file:
            entry.update(kit=None, reason="This entry has no spec file, "
                                           "so no kit can be generated.")
            kits[slug] = entry
            continue
        spec = RobotSpec.from_json((REPO / spec_file).read_text())
        if getattr(spec, "wheel", None) is None:
            entry.update(
                kit=None,
                reason="No take-apart kit is defined for this robot yet — "
                       "the kit generator builds kits for wheeled ground "
                       "robots from the spec's wheel block, and this "
                       "spec has no wheels.",
            )
            kits[slug] = entry
            continue
        entry["kit"] = kit_for(spec)
        kits[slug] = entry
    doc = {
        "note": "Generated by tools/build_parts_kits.py from each "
                "entry's spec via src/robotforge/cad.py (the same "
                "generator behind `robotforge cad`). Parts, quantities "
                "and parameter values are the generator's own output; "
                "kit: null means the generator defines no kit for that "
                "spec and the site must say so.",
        "kits": kits,
    }
    out = REPO / "catalog" / "parts-kits.json"
    out.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    have = [s for s, e in kits.items() if e.get("kit")]
    print(f"wrote {out.relative_to(REPO)}: kits for "
          f"{len(have)}/{len(kits)} entries -> {', '.join(have)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
