# Assembly + index
def _pos_xy(position: str, spec: RobotSpec) -> tuple[float, float]:
    """Sensor placement from the spec's free-text position — a layout
    assumption, always commented as such in the assembly file."""
    p = position.lower()
    x = 0.0
    y = 0.0
    if "front" in p:
        x = spec.length_m / 2.0
    elif "rear" in p or "back" in p:
        x = -spec.length_m / 2.0
    if "left" in p:
        y = spec.width_m / 4.0
    elif "right" in p:
        y = -spec.width_m / 4.0
    return x, y


def _assembly(spec: RobotSpec, plan: list[tuple[PartInfo, str]]) -> str:
    files = {info.filename for info, _ in plan}
    L = spec.length_m * 1000.0
    W = spec.width_m * 1000.0
    H = spec.height_m * 1000.0
    clearance = spec.ground_clearance_m * 1000.0
    r_mm = spec.wheel.diameter_m * 1000.0 / 2.0
    w_mm = spec.wheel.width_m * 1000.0
    positions = wheel_positions(spec)

    head = [
        f"// Assembly — the whole {spec.name}, built from the parts kit.",
        "// Generated by RobotForge (robotforge cad).",
        "//",
        "// Open this file in OpenSCAD: every part comes from the files in",
        "// parts/ (this file only positions them — edit a part in its own",
        "// file and the assembly follows). Hide a part by putting ! or #",
        "// in front of its line; spread the robot apart with explode_mm.",
        "//",
        "// Placement uses the same conventions as the RobotForge URDF:",
        "// ground is z = 0, wheel axles sit at wheel-radius height, wheel",
        "// X/Y positions are the generator's, and the chassis plate's",
        "// underside sits at the spec's ground clearance (the plate is",
        "// the deck; the spec height is the overall envelope, reached by",
        "// the sensor posts). Sensor positions come from the spec's",
        "// free-text position words — a layout assumption, not a survey.",
        "// Units: mm.",
    ]
    if is_estimated(spec):
        head += [
            "//",
            "// *** ESTIMATED — drafted from a PHOTO. Every dimension is",
            "// an estimate, not a measurement. ***",
        ]
    if spec.drivetrain not in ("differential", "skid_steer"):
        head += [
            "//",
            f"// Note: drivetrain '{spec.drivetrain}' uses the count-based",
            "// wheel layout (same day-1 convention as the URDF); steering",
            "// or track geometry is not modeled.",
        ]
    head += ["", "// How far to spread parts apart when exploding the view.",
             "explode_mm = 0;  // try 30", ""]
    for info, _ in plan:
        head.append(f"use <{info.filename}>")
    head.append("")

    body: list[str] = []
    body += [
        "// Ghost ground plane (never exported — display only).",
        f"%translate([0, 0, -2]) cube([{_n(L * 1.5)}, {_n(W * 1.8)}, 2], center = true);",
        "",
        "// Chassis plate — underside at the spec's ground clearance.",
        f"translate([0, 0, {_n(clearance)}]) chassis_plate();",
        "",
        "// Wheels — axle height = wheel radius, positions per the URDF layout.",
    ]
    for (x, y) in positions:
        body.append(
            f"translate([{_n(x * 1000.0)}, {_n(y * 1000.0)} + "
            f"{'explode_mm' if y > 0 else '-explode_mm'}, {_n(r_mm)}]) "
            f"rotate([90, 0, 0]) translate([0, 0, {_n(-w_mm / 2.0)}]) wheel();")
    body += ["", "// Motor mounts — one per wheel, flange under the deck edge."]
    for (x, y) in positions:
        if y > 0:
            body.append(
                f"translate([{_n(x * 1000.0)}, {_n(W / 2.0 - PLATE_THICKNESS_MM)}, 0]) "
                f"motor_mount();")
        else:
            body.append(
                f"translate([{_n(x * 1000.0)}, {_n(-(W / 2.0 - PLATE_THICKNESS_MM))}, 0]) "
                f"mirror([0, 1, 0]) motor_mount();")
    if "parts/caster.scad" in files:
        cx = L / 2.0 - spec.ground_clearance_m * 1000.0
        body += ["", "// Ball casters, front and rear (two-wheel layout).",
                 f"translate([{_n(cx)}, 0, 0]) caster();",
                 f"translate([{_n(-cx)}, 0, 0]) caster();"]
    deck_top = clearance + PLATE_THICKNESS_MM
    for s in spec.sensors:
        if s.kind == "lidar_2d" and "parts/lidar_mount.scad" in files:
            x, y = _pos_xy(s.position, spec)
            body += ["", "// Lidar mount — post stands on the deck, disc "
                         "reaches the overall height.",
                     f"translate([{_n(x * 1000.0)}, {_n(y * 1000.0)}, "
                     f"{_n(deck_top)} + explode_mm]) lidar_mount();"]
        elif s.kind in ("rgb_camera", "depth_camera") and \
                "parts/camera_bracket.scad" in files:
            x, _y = _pos_xy(s.position, spec)
            zb = clearance + H / 2.0 - CAM_BRACKET_H_MM / 2.0
            if x >= 0:
                body += ["", f"// Camera bracket — {s.position} face, "
                             "mid-height.",
                         f"translate([{_n(L / 2.0)}, 0, {_n(zb)}]) "
                         f"rotate([0, 0, -90]) camera_bracket();"]
            else:
                body += ["", f"// Camera bracket — {s.position} face, "
                             "mid-height.",
                         f"translate([{_n(-L / 2.0)}, 0, {_n(zb)}]) "
                         f"rotate([0, 0, 90]) camera_bracket();"]
        elif s.kind == "ultrasonic" and \
                "parts/ultrasonic_bracket.scad" in files:
            x, _y = _pos_xy(s.position, spec)
            if x >= 0:
                body += ["", "// Ultrasonic bracket — front face at deck level.",
                         f"translate([{_n(L / 2.0)}, 0, {_n(deck_top)}]) "
                         f"rotate([0, 0, -90]) ultrasonic_bracket();"]
            else:
                body += ["", "// Ultrasonic bracket — rear face at deck level.",
                         f"translate([{_n(-L / 2.0)}, 0, {_n(deck_top)}]) "
                         f"rotate([0, 0, 90]) ultrasonic_bracket();"]
    return "\n".join(head + body) + "\n"


def _index(spec: RobotSpec, plan: list[tuple[PartInfo, str]]) -> str:
    lines = [
        f"# {spec.name} — take-apart parts kit",
        "",
        f"Generated by RobotForge (`robotforge cad`) from the spec for "
        f"**{spec.name}** ({spec.drivetrain}). Units: mm.",
    ]
    if is_estimated(spec):
        lines += [
            "",
            "> **ESTIMATED — this kit was drafted from a photo.** Every "
            "dimension is an estimate, not a measurement. Confirm the real "
            "dimensions before printing anything that must fit.",
        ]
    lines += [
        "",
        "## Parts",
        "",
        "| Part | File | Qty | What it does | Key dimensions | Print notes |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for info, _ in plan:
        lines.append(f"| {info.name} | `{info.filename}` | {info.qty} | "
                     f"{info.does} | {info.dims} | {info.print_note} |")
    unprinted = [s for s in spec.sensors
                 if s.kind in ("imu", "gps", "encoder", "bumper",
                               "depth_camera", "rgb_camera", "lidar_2d",
                               "ultrasonic")]
    represented = {"lidar_2d", "rgb_camera", "depth_camera", "ultrasonic"}
    leftover = [s for s in unprinted if s.kind not in represented]
    if leftover:
        lines += ["", "## In the spec, but not separate printed parts", ""]
        for s in leftover:
            lines.append(f"- **{s.kind}** ({s.position}) — internal or "
                         f"wheel-mounted sensor; it rides inside the "
                         f"chassis and has no bracket in this kit.")
    lines += [
        "",
        "## Assembly",
        "",
        "Open `assembly.scad` in OpenSCAD to see the whole robot. It only "
        "positions the part files — edit a part in its own file and the "
        "assembly follows. Set `explode_mm` at the top of `assembly.scad` "
        "to spread the parts apart, and prefix any part's line with `!` "
        "to isolate it.",
        "",
        "## Editing these files in other CAD software",
        "",
        "Open any `.scad` file directly in OpenSCAD (free) or in FreeCAD "
        "(which reads `.scad` through its OpenSCAD workbench). To use a "
        "part in Tinkercad, Fusion 360, Blender or a slicer, render its "
        "STL (`robotforge cad <spec> --stl` when an `openscad` binary is "
        "available, or File > Export in OpenSCAD) and import the STL there.",
        "",
    ]
    return "\n".join(lines)


def generate_kit(spec: RobotSpec) -> dict[str, str]:
    """Kit contents as {relative path: file text}, deterministic order:
    parts (canonical order), then assembly.scad, then parts_index.md."""
    plan = _plan(spec)
    kit: dict[str, str] = {}
    for info, text in plan:
        kit[info.filename] = text
    kit["assembly.scad"] = _assembly(spec, plan)
    kit["parts_index.md"] = _index(spec, plan)
    return kit


def write_kit(spec: RobotSpec, out_dir: Path) -> list[PartInfo]:
    kit = generate_kit(spec)
    for rel, text in kit.items():
        dest = out_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
    return part_infos(spec)


def render_stls(kit_dir: Path) -> list[Path] | None:
    """Render per-part + assembly STLs with a local openscad binary.

    Returns None when no openscad binary is on PATH (rendering skipped —
    generation is the deliverable). Raises subprocess.CalledProcessError
    if the binary exists but a render fails.
    """
    exe = shutil.which("openscad")
    if exe is None:
        return None
    stl_dir = kit_dir / "stl"
    stl_dir.mkdir(parents=True, exist_ok=True)
    rendered: list[Path] = []
    scads = sorted((kit_dir / "parts").glob("*.scad"))
    scads.append(kit_dir / "assembly.scad")
    for scad in scads:
        dest = stl_dir / (scad.stem + ".stl")
        subprocess.run([exe, "-o", str(dest), str(scad)],
                       check=True, capture_output=True, text=True,
                       timeout=600)
        rendered.append(dest)
    return rendered
