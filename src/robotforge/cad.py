# ---------------------------------------------------------------------------
# Assumption defaults (NOT in the spec — always labeled as such in output)
PLATE_THICKNESS_MM = 4.0      # deck / bracket plate stock
CORNER_RADIUS_MM = 6.0        # chassis corner rounding
MOUNT_HOLE_D_MM = 3.4         # M3 bolt clearance hole
MOUNT_HOLE_INSET_MM = 12.0    # chassis hole centre distance from edges
SHAFT_D_MM = 6.0              # typical small DC gearmotor shaft
LIDAR_DISC_D_MM = 70.0        # typical 2D lidar puck (e.g. RPLIDAR class)
POST_D_MM = 12.0              # lidar post diameter
CAM_BRACKET_W_MM = 44.0       # small camera (Pi-camera class) bracket
CAM_BRACKET_H_MM = 34.0
LENS_HOLE_D_MM = 12.0
ULTRA_CAN_D_MM = 16.0         # HC-SR04-style transducer can
ULTRA_CAN_SPACING_MM = 26.0   # HC-SR04-style can centre spacing
ULTRA_PLATE_W_MM = 52.0
ULTRA_PLATE_H_MM = 20.0


def _n(v: float) -> str:
    """Deterministic number formatting: 420, 26.4, 0.5 — never 420.0000001."""
    r = round(float(v), 3)
    if r == int(r):
        return str(int(r))
    return f"{r:.3f}".rstrip("0").rstrip(".")


def _mm(metres: float) -> str:
    return _n(metres * 1000.0)


def is_estimated(spec: RobotSpec) -> bool:
    """Photo drafts carry their provenance in the spec description
    (photo.py prefixes it with "Photo draft (all dimensions ESTIMATED):").
    The predicate itself lives in schema.py (``spec_is_estimated``) so
    validate and the gate share exactly the same test."""
    return spec_is_estimated(spec)


def kit_slug(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug or "robot"


def wheel_positions(spec: RobotSpec) -> list[tuple[float, float]]:
    """Wheel (x, y) centres in metres — mirrors urdf.py exactly: a 2-wheel
    layout gets the pair at the chassis centre; anything else gets the
    front/rear corner pairs truncated to the spec's wheel count."""
    wheel_x = spec.length_m / 2.0 - spec.wheel.diameter_m / 2.0
    wheel_y = spec.width_m / 2.0 + spec.wheel.width_m / 2.0
    if spec.wheel.count == 2:
        return [(0.0, wheel_y), (0.0, -wheel_y)]
    return [(wheel_x, wheel_y), (wheel_x, -wheel_y),
            (-wheel_x, wheel_y), (-wheel_x, -wheel_y)][:spec.wheel.count]


@dataclass
class PartInfo:
    name: str        # human name, e.g. "Wheel"
    filename: str    # kit-relative path, e.g. "parts/wheel.scad"
    qty: int
    does: str        # one plain-language line: what the part does
    dims: str        # key dimensions line for the index
    print_note: str  # beginner print note (a suggestion, labeled as such)


# ---------------------------------------------------------------------------
# Shared file headers
def _header(spec: RobotSpec, title: str, what: str,
            tweaks: list[tuple[str, str]]) -> str:
    what_lines = textwrap.wrap(what, width=72)
    lines = [
        f"// {title} — one part of the {spec.name} take-apart kit,",
        "// generated by RobotForge (robotforge cad). Open this file on its",
        "// own in OpenSCAD to see and edit just this part.",
        "//",
        f"// What this is: {what_lines[0]}",
    ]
    lines += [f"//   {extra}" for extra in what_lines[1:]]
    lines += [
        "//",
        "// Scope: a printable approximation for visualization / fabrication",
        "// reference. No tolerances, fasteners, wiring or internal structure",
        "// are claimed. Numbers marked 'assumption' did not come from the",
        "// robot spec — they are typical values a beginner can adjust.",
        "// Units: mm throughout (OpenSCAD is unitless; mm is the",
        "// 3D-printing convention, so spec metres are x1000 here).",
    ]
    if is_estimated(spec):
        lines += [
            "//",
            "// *** ESTIMATED — this kit was drafted from a PHOTO. Every",
            "// dimension is an estimate, not a measurement. Confirm the",
            "// real dimensions before printing anything that must fit. ***",
        ]
    lines += ["//", "// Beginner tweaks — the parameters worth changing:"]
    for name, why in tweaks:
        lines.append(f"//   {name} — {why}")
    lines.append("")
    return "\n".join(lines) + "\n"


def _param(name: str, value_mm: float, source: str) -> str:
    return f"{name} = {_n(value_mm)};  // {source}"


