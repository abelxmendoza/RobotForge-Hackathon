"""Take-apart CAD kit generation from a validated RobotSpec.

One combined model file is hard for a beginner to use, so `robotforge cad`
emits a kit instead:

- ``parts/<part>.scad`` — one standalone OpenSCAD file per physical part
  (chassis plate, wheel, motor mount, ...), each modeled in a natural
  print pose with beginner-friendly comments and a small set of named
  parameters a newcomer would actually tweak.
- ``assembly.scad`` — imports the part files and positions them with the
  same geometry conventions as urdf.py (wheel placement, axle height,
  chassis reference at the spec's ground clearance), so the whole robot
  is visible and parts can be hidden or exploded.
- ``parts_index.md`` — every part, its file, quantity, key dimensions and
  print notes (labeled as suggestions).

Honest scope, printed in every generated file: this is a printable
*approximation* for visualization / fabrication reference. No tolerances,
fasteners, wiring, or internal structure are claimed. Dimensions that did
not come from the spec (plate thicknesses, hole sizes, a typical lidar
puck diameter, ...) are emitted as parameters whose comments say
"assumption — not in the spec". If the spec is a photo draft, its
dimensions are estimates and every file in the kit says so.

Units: OpenSCAD is unitless; the convention here is **mm** (the
3D-printing ecosystem's unit — slicers assume mm), so every spec metre
value is x1000 in the parameters, with the source field named in a
comment. Generation is deterministic: same spec in, byte-identical kit
out (no timestamps inside any file).
"""
from __future__ import annotations

