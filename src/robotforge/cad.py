# Part generators. Each returns (PartInfo, scad_text). Parts are modeled in
# a natural print pose resting on z=0 unless their header says otherwise.
def _chassis_plate(spec: RobotSpec) -> tuple[PartInfo, str]:
    L = spec.length_m * 1000.0
    W = spec.width_m * 1000.0
    info = PartInfo(
        name="Chassis plate", filename="parts/chassis_plate.scad", qty=1,
        does="The deck everything else bolts to.",
        dims=f"{_mm(spec.length_m)} x {_mm(spec.width_m)} mm footprint, "
             f"{_n(PLATE_THICKNESS_MM)} mm thick",
        print_note="Print flat as modeled. Suggestion: 3-4 walls, ~25% infill.")
    body = f'''{_header(spec, "Chassis plate",
        "a flat deck plate with rounded corners and four bolt holes. "
        "In the assembly it sits at the spec's ground clearance.",
        [("plate_thickness_mm", "thicker = stiffer and heavier"),
         ("mount_hole_inset_mm", "moves the corner bolt holes in or out"),
         ("corner_radius_mm", "bigger = rounder, friendlier corners")])}
// ---- Parameters (edit me) ----
{_param("chassis_length_mm", L, "from spec length_m")}
{_param("chassis_width_mm", W, "from spec width_m")}
{_param("plate_thickness_mm", PLATE_THICKNESS_MM, "assumption — not in the spec")}
{_param("corner_radius_mm", CORNER_RADIUS_MM, "assumption — not in the spec")}
{_param("mount_hole_diameter_mm", MOUNT_HOLE_D_MM, "assumption — M3 bolt clearance")}
{_param("mount_hole_inset_mm", MOUNT_HOLE_INSET_MM, "assumption — not in the spec")}

module chassis_plate() {{
  difference() {{
    // Rounded rectangle: hull of four corner cylinders.
    hull() {{
      for (sx = [-1, 1], sy = [-1, 1])
        translate([sx * (chassis_length_mm / 2 - corner_radius_mm),
                   sy * (chassis_width_mm / 2 - corner_radius_mm), 0])
          cylinder(h = plate_thickness_mm, r = corner_radius_mm);
    }}
    // Four corner bolt holes.
    for (sx = [-1, 1], sy = [-1, 1])
      translate([sx * (chassis_length_mm / 2 - mount_hole_inset_mm),
                 sy * (chassis_width_mm / 2 - mount_hole_inset_mm), -1])
        cylinder(h = plate_thickness_mm + 2, d = mount_hole_diameter_mm);
  }}
}}

chassis_plate();
'''
    return info, body


def _wheel(spec: RobotSpec) -> tuple[PartInfo, str]:
    d = spec.wheel.diameter_m * 1000.0
    w = spec.wheel.width_m * 1000.0
    hub_d = round(d * 0.4, 1)
    light_r = d * 0.32
    light_d = max(4.0, round(d * 0.12, 1))
    qty = len(wheel_positions(spec))
    info = PartInfo(
        name="Wheel", filename="parts/wheel.scad", qty=qty,
        does="Rolls on the ground; one per wheel position on the robot.",
        dims=f"{_mm(spec.wheel.diameter_m)} mm diameter x "
             f"{_mm(spec.wheel.width_m)} mm wide, {_n(SHAFT_D_MM)} mm shaft hole",
        print_note="Print flat as modeled. Suggestion: print one first and "
                   "check the shaft fit before printing the rest.")
    body = f'''{_header(spec, "Wheel",
        "a simple flat hub wheel with a motor-shaft hole and lightening "
        "holes. One file, printed once per wheel (see the parts index "
        "for the quantity).",
        [("wheel_diameter_mm", "bigger = faster and more ground clearance, "
          "but less torque"),
         ("wheel_width_mm", "wider = more grip, needs more room beside the chassis"),
         ("shaft_diameter_mm", "MUST match your motor's shaft — measure it")])}
// ---- Parameters (edit me) ----
{_param("wheel_diameter_mm", d, "from spec wheel.diameter_m")}
{_param("wheel_width_mm", w, "from spec wheel.width_m")}
{_param("shaft_diameter_mm", SHAFT_D_MM, "assumption — typical DC gearmotor shaft; measure yours")}
{_param("hub_diameter_mm", hub_d, "derived — 0.4 x wheel diameter, for looks/strength")}
{_param("lightening_hole_diameter_mm", light_d, "derived — decorative; delete the loop below for a solid wheel")}

module wheel() {{
  difference() {{
    cylinder(h = wheel_width_mm, d = wheel_diameter_mm);
    // Motor shaft hole, straight through.
    translate([0, 0, -1])
      cylinder(h = wheel_width_mm + 2, d = shaft_diameter_mm);
    // Four lightening holes around the hub.
    for (a = [0 : 90 : 270])
      translate([{_n(light_r)} * cos(a), {_n(light_r)} * sin(a), -1])
        cylinder(h = wheel_width_mm + 2, d = lightening_hole_diameter_mm);
  }}
}}

wheel();
'''
    return info, body


def _motor_mount(spec: RobotSpec) -> tuple[PartInfo, str]:
    r_mm = spec.wheel.diameter_m * 1000.0 / 2.0
    w_mm = spec.wheel.width_m * 1000.0
    mount_w = w_mm + 16.0
    mount_h = max(r_mm + SHAFT_D_MM / 2.0 + 8.0,
                  spec.ground_clearance_m * 1000.0 + PLATE_THICKNESS_MM + 8.0)
    qty = len(wheel_positions(spec))
    info = PartInfo(
        name="Motor mount", filename="parts/motor_mount.scad", qty=qty,
        does="Side plate that holds one drive motor so its shaft lines up "
             "with a wheel's axle.",
        dims=f"{_n(mount_w)} mm wide plate, shaft hole at axle height "
             f"{_n(r_mm)} mm",
        print_note="Suggestion: 40% infill — this part takes the motor's "
                   "twist. The motor itself is not a printed part.")
    body = f'''{_header(spec, "Motor mount",
        "a side plate with a motor-shaft hole and a bolting flange. The "
        "plate stands in the ground frame: its shaft hole sits exactly at "
        "the wheel axle height, and its top edge reaches the chassis "
        "plate so the two can be bolted together.",
        [("shaft_center_height_mm", "the axle height — must equal the wheel "
          "radius or the wheel lifts off the ground"),
         ("mount_thickness_mm", "thicker = stronger, heavier"),
         ("mount_width_mm", "front-to-back size of the plate")])}
// ---- Parameters (edit me) ----
{_param("shaft_center_height_mm", r_mm, "from spec wheel radius (diameter_m / 2) — the axle height above ground")}
{_param("mount_width_mm", mount_w, "derived — wheel width + 16 mm of plate around the motor")}
{_param("mount_height_mm", mount_h, "derived — reaches from the ground past the axle to the chassis plate")}
{_param("mount_thickness_mm", PLATE_THICKNESS_MM, "assumption — not in the spec")}
{_param("shaft_hole_diameter_mm", SHAFT_D_MM + 0.4, "derived — shaft diameter + 0.4 mm slip fit")}
{_param("flange_depth_mm", 16.0, "assumption — how far the bolting flange reaches under the chassis")}
{_param("flange_hole_diameter_mm", MOUNT_HOLE_D_MM, "assumption — M3 bolt clearance")}

module motor_mount() {{
  difference() {{
    union() {{
      // Vertical side plate (shaft hole goes through it, along Y).
      translate([-mount_width_mm / 2, 0, 0])
        cube([mount_width_mm, mount_thickness_mm, mount_height_mm]);
      // Bolting flange along the bottom, reaching toward the robot (-Y).
      translate([-mount_width_mm / 2, -flange_depth_mm, 0])
        cube([mount_width_mm, flange_depth_mm, mount_thickness_mm]);
    }}
    // Motor shaft hole, at axle height.
    translate([0, -1, shaft_center_height_mm])
      rotate([-90, 0, 0])
        cylinder(h = mount_thickness_mm + 2, d = shaft_hole_diameter_mm);
    // Two flange bolt holes.
    for (sx = [-1, 1])
      translate([sx * mount_width_mm / 4, -flange_depth_mm / 2, -1])
        cylinder(h = mount_thickness_mm + 2, d = flange_hole_diameter_mm);
  }}
}}

motor_mount();
'''
    return info, body


