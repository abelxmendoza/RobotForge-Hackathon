# Kit assembly: which parts a spec implies, in canonical order.
def _plan(spec: RobotSpec) -> list[tuple[PartInfo, str]]:
    plan: list[tuple[PartInfo, str]] = []
    plan.append(_chassis_plate(spec))
    plan.append(_wheel(spec))
    plan.append(_motor_mount(spec))
    if spec.wheel.count == 2:
        plan.append(_caster(spec))
    kinds = [s.kind for s in spec.sensors]
    if "lidar_2d" in kinds:
        plan.append(_lidar_mount(
            spec, next(s for s in spec.sensors if s.kind == "lidar_2d")))
    cams = [s for s in spec.sensors if s.kind in ("rgb_camera", "depth_camera")]
    for s in cams:
        info, text = _camera_bracket(spec, s)
        info.qty = len(cams)
        plan.append((info, text))
        break  # one parameterized file covers every camera of this plan
    ultras = [s for s in spec.sensors if s.kind == "ultrasonic"]
    for s in ultras:
        info, text = _ultrasonic_bracket(spec, s)
        info.qty = len(ultras)
        plan.append((info, text))
        break
    return plan


def part_infos(spec: RobotSpec) -> list[PartInfo]:
    return [info for info, _ in _plan(spec)]


