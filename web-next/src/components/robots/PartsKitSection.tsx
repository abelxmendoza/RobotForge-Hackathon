import Link from "next/link";
import { kitOf } from "@/lib/data";
import SourcingLinks from "./SourcingLinks";

/* The take-apart parts kit for one Robodex entry, rendered from
   catalog/parts-kits.json — data generated by tools/build_parts_kits.py
   out of src/robotforge/cad.py, the same generator behind
   `robotforge cad`. Part names, quantities, prose and parameter
   values are the generator's own output for this robot's spec.
   When the generator defines no kit for a spec (today: anything
   without wheels), the section says so with the recorded reason —
   parts are never invented for an entry. */

function fmtMm(v: number): string {
  return Number.isInteger(v) ? v.toFixed(0) : String(v);
}

export default function PartsKitSection({ slug }: { slug: string }) {
  const entry = kitOf(slug);
  const kit = entry?.kit ?? null;
  return (
    <section className="section" id="parts-kit">
      <h2>Parts kit</h2>
      <p className="sub">
        The take-apart kit <code>robotforge cad</code> generates from this
        robot&apos;s spec: every part the generator defines, what it does,
        and the parameters worth tweaking with the values this robot&apos;s
        kit ships with. Each parameter carries the generator&apos;s own
        source label — <em>from spec</em> numbers come out of the spec,{" "}
        <em>derived</em> numbers are computed from them, and{" "}
        <em>assumption</em> numbers are typical values the spec does not
        carry. The search links under each part open vendor searches
        for it — search links only: this site never shows a price, a
        stock level or an availability claim. To turn a kit into a
        shopping-ready list, run it through the{" "}
        <Link href={kit ? `/bom/?kit=${slug}` : "/bom/"}>BOM wizard</Link>.
      </p>
      {kit ? (
        <>
          {kit.estimated ? (
            <div className="callout bad" style={{ marginBottom: 12 }}>
              <span>
                ESTIMATED kit — this entry&apos;s spec was drafted from a
                photo, so every dimension in the kit is an estimate, not a
                measurement. The generated files say the same thing.
              </span>
            </div>
          ) : null}
          {kit.parts.map((part) => (
            <div className="card" key={part.file} style={{ marginTop: 12 }}>
              <div className="card-head">
                <h3 style={{ fontSize: "var(--fs-md)" }}>
                  {part.name} ×{part.qty}
                </h3>
                <code>{part.file}</code>
              </div>
              <p style={{ marginTop: 12 }}>{part.does}</p>
              <p className="muted" style={{ fontSize: "var(--fs-sm)" }}>
                {part.dims}
              </p>
              {part.params.length ? (
                <div className="table-scroll" style={{ marginTop: 12 }}>
                  <table className="data">
                    <thead>
                      <tr>
                        <th>Parameter</th>
                        <th>Value</th>
                        <th>Where the number comes from</th>
                      </tr>
                    </thead>
                    <tbody>
                      {part.params.map((p) => (
                        <tr key={p.name}>
                          <td><code>{p.name}</code></td>
                          <td className="num">{fmtMm(p.value_mm)} mm</td>
                          <td>{p.source}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              ) : null}
              <p className="prov" style={{ marginTop: 12 }}>
                <span><strong>Print note:</strong> {part.print_note}</span>
              </p>
              <SourcingLinks query={`${part.name} ${part.dims}`} />
            </div>
          ))}
        </>
      ) : (
        <div className="card">
          <p className="state-box">
            {entry?.reason ??
              "No parts kit data is recorded for this entry yet."}
          </p>
        </div>
      )}
    </section>
  );
}
