export const LOOK_MAX_CHARS = 200;

/* One of each part, for the 3D service's prompt ("a single wheel"). */
const SINGULAR: Record<string, string> = {
  wheel: 'robot wheel with its tyre', rotor: 'propeller', camera: 'camera module', lidar: 'lidar sensor',
  ultrasonic: 'ultrasonic distance sensor', caster: 'ball caster', mount: 'motor mount bracket',
  battery: 'battery pack', fc: 'flight controller board', arm: 'robot arm', leg: 'robot leg',
  head: 'robot head', gripper: 'robot gripper', plate: 'flat chassis deck plate', frame: 'drone frame', body: 'robot body shell',
};

const num = (v: unknown): number => (typeof v === 'number' && Number.isFinite(v) ? v : 0);
const mm = (m: number): string => `${parseFloat((m * 1000).toFixed(1))} mm`;
const times = (k: number): string => `×${parseFloat(k.toFixed(2))}`;

/* "90 mm", "9 cm", "0.09 m", "3.5 in", '3.5"' -> metres. Only an
 * explicit unit counts: a bare number is never guessed. */
export function parseLength(text: string): number | null {
  const m = text.match(/(\d+(?:\.\d+)?|\.\d+)\s*(mm|millimet(?:er|re)s?|cm|centimet(?:er|re)s?|met(?:er|re)s?|m|inch(?:es)?|in|"|”)(?![a-z])/i);
  if (!m) return null;
  const v = Number(m[1]);
  const u = m[2].toLowerCase();
  if (u.startsWith('mm') || u.startsWith('milli')) return v / 1000;
  if (u.startsWith('cm') || u.startsWith('centi')) return v / 100;
  if (u === 'm' || u.startsWith('met')) return v;
  return v * 0.0254;
}

/* Which robot a phrase is about: a saved robot named in it, else the
 * robot open in the Workshop. Names must match one saved robot. */
export function pickRobot<R extends { id: string; name: string }>(
  text: string, robots: R[], openRobotId?: string,
): R | null {
  const q = text.toLowerCase();
  const named = robots.filter((r) => {
    const n = r.name.toLowerCase().trim();
    return n.length > 1 && new RegExp(`(^|[^a-z0-9])${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?:'s|’s)?([^a-z0-9]|$)`).test(q);
  });
  if (named.length === 1) return named[0];
  if (named.length > 1) return null;
  return robots.find((r) => r.id === openRobotId) ?? null;
}

function sizeFields(part: SizePart, dim: Dim, spec: Spec): { path: string; label: string }[] {
  if (part === 'wheels') {
    return dim === 'wide' ? [{ path: 'wheel.width_m', label: 'Wheel width' }]
      : [{ path: 'wheel.diameter_m', label: 'Wheel diameter' }];
  }
  if (part === 'props') return [{ path: 'rotors.prop_diameter_m', label: 'Propeller diameter' }];
  if (part === 'clearance') return [{ path: 'ground_clearance_m', label: 'Ground clearance' }];
  const aerial = Boolean(spec?.rotors);
  const L = { path: 'length_m', label: aerial ? 'Motor span, front to back' : 'Body length' };
  const W = { path: 'width_m', label: aerial ? 'Motor span, side to side' : 'Body width' };
  const H = { path: 'height_m', label: 'Body height' };
  if (dim === 'long') return [L];
  if (dim === 'wide') return [W];
  if (dim === 'tall') return [H];
  return [L, W];
}

function viewIdFor(part: SizePart, spec: Spec): string {
  if (part === 'wheels') return 'wheel';
  if (part === 'props') return 'rotor';
  if (spec?.rotors) return 'frame';
  if (spec?.legs) return 'body';
  if (spec?.drivetrain === 'robotic_arm') return 'base';
  return 'plate';
}

const PART_LABEL: Record<SizePart, string> = {
  wheels: 'the wheels', props: 'the propellers', body: 'the body', clearance: 'the ground clearance',
};

function hasPart(part: SizePart, spec: Spec): string | null {
  if (part === 'wheels' && !(num(spec?.wheel?.diameter_m) > 0)) return 'This robot has no wheels on record, so there is nothing to resize.';
  if (part === 'props' && !(num(spec?.rotors?.prop_diameter_m) > 0)) return 'This robot has no propellers on record, so there is nothing to resize.';
  if (part === 'body' && !(num(spec?.length_m) > 0 && num(spec?.width_m) > 0)) return 'This robot has no body size on record yet. Add its length and width in Specs first.';
  return null;
}

/* Words -> a size plan for ONE part, an error message, or null when
 * the words are not a size edit at all (so other grammars can try).
 * Throws Error(message) for an edit that is understood but can't be
 * done; the caller shows the message and changes nothing. */
export function parsePartEdit(text: string, spec: Spec): PartEditPlan | null {
  const q = text.toLowerCase().replace(/[’']s\b/g, '').replace(/[.!?]+$/, '').trim();
  if (isLookPhrase(q)) return null;
  const verb = /\b(make|set|change|resize|scale|give|raise|lower|increase|decrease|grow|shrink|use|put|enlarge|reduce)\b/.test(q)
    || /^(bigger|larger|smaller|wider|narrower|longer|shorter|taller|thicker|thinner)\b/.test(q);
  if (!verb) return null;
  const hits = ALIASES.filter((a) => a.re.test(q));
  /* "ground clearance" also matches nothing else; "the deck height"
   * is the body. Two different parts in one phrase is not one edit. */
  const parts = [...new Set(hits.map((h) => h.part))];
  if (!parts.length) return null;
  if (parts.length > 1) throw new Error('One part at a time, please: say which part to change, like “make the wheels bigger”.');
  const part = parts[0];
  const missing = hasPart(part, spec);
  if (missing) throw new Error(missing);

  let dim: Dim = 'size';
  if (/\b(wider|narrower|thicker|thinner|wide|width|thick)\b/.test(q)) dim = 'wide';
  else if (/\b(longer|long|length)\b/.test(q)) dim = 'long';
  else if (/\b(taller|tall|height|higher)\b/.test(q) && part === 'body') dim = 'tall';
  else if (/\bshorter\b/.test(q) && part === 'body') dim = 'long';
  if (part === 'props' && dim !== 'size') dim = 'size';
  const fields = sizeFields(part, dim, spec);

  const target = parseLength(q);
  let factor: number | null = null;
  const pct = q.match(/(\d+(?:\.\d+)?)\s*%/);
  const up = /\b(bigger|larger|wider|longer|taller|thicker|raise|higher|increase|grow|enlarge|more)\b/.test(q);
  const down = /\b(smaller|narrower|shorter|thinner|lower|decrease|shrink|reduce|less)\b/.test(q);
  if (target == null) {
    if (/\b(twice|double)\b/.test(q)) factor = 2;
    else if (/\bhalf\b/.test(q)) factor = 0.5;
    else if (up === down) {
      if (/\d/.test(q)) throw new Error('Give the size with a unit, like “90 mm”, “9 cm” or “3.5 in”.');
      return null;
    } else {
      const amount = pct ? Number(pct[1]) / 100
        : /\b(a lot|much|way|far)\b/.test(q) ? 0.5
        : /\b(a bit|a little|slightly|a touch|bit)\b/.test(q) ? 0.1
        : 0.25;
      factor = up ? 1 + amount : 1 / (1 + amount);
    }
  } else if (fields.length > 1) {
    throw new Error('Say which way, like “make the body 30 cm long” or “make the body 20 cm wide”.');
  }

  const changes: PartChange[] = fields.map((f) => {
    const before = num(f.path.split('.').reduce((o: Spec, k) => (o ? o[k] : undefined), spec));
    let after = target != null ? target : before * (factor as number);
    after = Math.round(after * 10000) / 10000; // 0.1 mm
    return { path: f.path, label: f.label, before, after };
  });
  for (const c of changes) {
    if (!(c.before > 0) && part !== 'clearance') throw new Error(`${c.label} is not on record for this robot, so I can't scale it. Give an exact size, like “90 mm”.`);
    const floor = part === 'clearance' ? 0 : 0.005;
    if (c.after < floor || c.after > 3) throw new Error(`${c.label} of ${mm(c.after)} is outside what RobotForge models (5 mm to 3 m).`);
  }
  if (changes.every((c) => c.after === c.before)) throw new Error(`${PART_LABEL[part][0].toUpperCase()}${PART_LABEL[part].slice(1)} already ${part === 'wheels' || part === 'props' ? 'are' : 'is'} that size.`);
  return { kind: 'size', part, partLabel: PART_LABEL[part], viewId: viewIdFor(part, spec), phrase: text.trim().slice(0, 120), changes };
}

function isLookPhrase(q: string): boolean {
  return /\blook(?:s|ing)? like\b/.test(q)
    || /\b(?:regenerate|restyle|remodel|redesign|redraw)\b/.test(q)
    || /\bnew (?:3d )?(?:look|shape|model)\b/.test(q);
}

/* Words -> a look plan, or null when the words are not a look edit.
 * `present` is the list of part ids the robot's 3D model draws; a
 * part the model doesn't draw can't be regenerated. Throws for a
 * look edit that names no drawable part. */
export function parseLookEdit(text: string, present: string[]): PartLookPlan | null {
  const q = text.toLowerCase().replace(/[’']s\b/g, '').replace(/[.!?]+$/, '').trim();
  if (!isLookPhrase(q)) return null;
  const m = q.match(/^(?:please\s+)?(?:make|turn|give|regenerate|restyle|remodel|redesign|redraw)\s+(.+?)\s+(?:look(?:s|ing)? like|as|like|into|in the style of|with|a new (?:3d )?(?:look|shape|model)(?: of| like)?:?)\s+(.+)$/);
  const subject = m ? m[1] : q;
  const described = (m ? m[2] : '').replace(/^(?:a|an|the)\s+/, '').trim();
  const hit = LOOK_ALIASES.find((a) => a.re.test(subject));
  if (!hit) throw new Error('Name the part to regenerate, like “make the wheels look like knobby off-road tyres”.');
  if (!present.includes(hit.id)) throw new Error(`This robot's 3D model has no ${hit.label.replace(/^the /, '')}, so there is nothing to regenerate.`);
  if (!described) throw new Error(`Say what ${hit.label} should look like, like “make ${hit.label} look like …”.`);
  return {
    kind: 'look', viewId: hit.id, partLabel: hit.label,
    description: described.slice(0, LOOK_MAX_CHARS), phrase: text.trim().slice(0, 120),
  };
}

/* The text sent to the 3D service: one isolated part, described by
 * the owner's words. Kept here so the test suite pins what leaves
 * the browser (no robot record, no names, no ids). */
export function lookPrompt(plan: PartLookPlan): string {
  const part = SINGULAR[plan.viewId] ?? plan.partLabel.replace(/^the /, '');
  return `A single ${part} for a small hobby robot: ${plan.description}. One isolated part on its own, no robot body, no stand, no base, centred.`.slice(0, 600);
}

/* The spec after the edit. Only the planned paths are written. */
export function applyPartEdit(spec: Spec, plan: PartEditPlan): Spec {
  const next = JSON.parse(JSON.stringify(spec ?? {}));
  for (const c of plan.changes) {
    const keys = c.path.split('.');
    let o = next;
    for (const k of keys.slice(0, -1)) {
      if (!o[k] || typeof o[k] !== 'object') o[k] = {};
      o = o[k];
    }
    o[keys[keys.length - 1]] = c.after;
  }
  return next;
}

function leafDiff(a: Spec, b: Spec, prefix = ''): string[] {
  const out: string[] = [];
  const isObj = (v: unknown) => !!v && typeof v === 'object' && !Array.isArray(v);
  const keys = new Set([...Object.keys(a ?? {}), ...Object.keys(b ?? {})]);
  for (const k of keys) {
    const p = prefix ? `${prefix}.${k}` : k;
    const x = a ? a[k] : undefined;
    const y = b ? b[k] : undefined;
    if (isObj(x) || isObj(y)) out.push(...leafDiff(isObj(x) ? x : {}, isObj(y) ? y : {}, p));
    else if (JSON.stringify(x) !== JSON.stringify(y)) out.push(p);
  }
  return out;
}

/* Checks the edit: proves the rest of the robot is untouched, and
 * names what the new size would break or change. Only arithmetic on
 * the recorded fields; nothing is estimated that isn't labelled. */
export function checkPartEdit(before: Spec, after: Spec, plan: PartEditPlan): PartEditCheck {
  const changedPaths = leafDiff(before, after).sort();
  const planned = plan.changes.map((c) => c.path).sort();
  const restKept = JSON.stringify(changedPaths) === JSON.stringify(planned);
  const problems: string[] = [];
  const effects: string[] = [];
  const L = num(after.length_m);
  const W = num(after.width_m);
  const C = num(after.ground_clearance_m);
  const d = num(after.wheel?.diameter_m);
  const count = num(after.wheel?.count);
  const touches = (p: string) => planned.includes(p);

  if (d > 0) {
    if (count >= 4 && d > L / 2) {
      problems.push(`The front and rear wheels would overlap: each wheel (${mm(d)}) is more than half the body length (${mm(L)}).`);
    }
    if (C >= d) {
      problems.push(`The deck (${mm(C)} up) would sit above the tops of the wheels (${mm(d)}), so the wheels could not reach it.`);
    }
  }
  const pd = num(after.rotors?.prop_diameter_m);
  if (pd > 0 && num(after.rotors?.count) >= 4) {
    const gap = Math.min(L, W);
    if (pd > gap) problems.push(`Neighbouring propellers would hit each other: ${mm(pd)} propellers on motors ${mm(gap)} apart.`);
  }

  const k = (path: string) => {
    const c = plan.changes.find((x) => x.path === path);
    return c && c.before > 0 ? c.after / c.before : null;
  };
  const kd = k('wheel.diameter_m');
  if (kd) {
    effects.push(`Top speed ${times(kd)} at the same motor speed (speed = rpm × π × wheel diameter).`);
    effects.push(`Each motor needs ${times(kd)} the torque to push the same load (torque = force × wheel radius).`);
  }
  if (touches('wheel.width_m')) effects.push('Wider wheels grip more on soft ground and turn a little harder on the spot. The spec has no tyre model, so this is not computed.');
  const kp = k('rotors.prop_diameter_m');
  if (kp) {
    effects.push(`Rule of thumb, not a measurement: at the same motor speed thrust goes ${times(kp ** 4)} and the power the motors need ${times(kp ** 5)} (thrust ∝ diameter⁴, power ∝ diameter⁵).`);
  }
  if (touches('ground_clearance_m')) effects.push('Higher clearance clears bigger bumps but raises the centre of mass, so the robot tips sooner on slopes.');
  if (touches('length_m') || touches('width_m')) {
    effects.push(plan.part === 'body' && after.rotors ? 'The motors move out with the frame; the propellers keep their size.' : 'The wheels move with the body edges and keep their size.');
  }
  effects.push('Mass is unchanged in the record. A real bigger part usually weighs more, so update Total mass in Specs if you know it.');
  return { changedPaths, restKept, problems, effects };
}

/* One line per change, for the chat bubble and the version note. */
export function describeChanges(plan: PartEditPlan): string {
  return plan.changes.map((c) => `${c.label} ${mm(c.before)} → ${mm(c.after)}`).join('; ');
}

