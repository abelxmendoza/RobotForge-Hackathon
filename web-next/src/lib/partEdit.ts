/* Wrench one-part edits: "make the wheels bigger" changes ONE part of
 * a robot and nothing else (the Kimi 3D Make idea: keep the rest,
 * change this part).
 *
 * Two kinds of edit, both parsed here from plain words:
 *
 *   1. SIZE edits ("make the wheels bigger", "make the props 5 inch",
 *      "make the body 30 cm long", "raise the ground clearance to
 *      20 mm"). They change the spec fields that part is drawn from,
 *      so the 3D model, the drive math and the Forge checks all follow.
 *      They need no AI and no key: the words map to exact fields.
 *
 *   2. LOOK edits ("make the wheels look like knobby off-road tyres").
 *      Words can't say that in spec fields, so the part's 3D shape is
 *      regenerated by a text-to-3D service behind the Worker's
 *      /part-mesh route (lib/partMesh.ts) and fitted into the part's
 *      own space in the model. The spec is never touched by a look
 *      edit, and the new shape is always captioned as generated.
 *
 * Nothing is applied here: this module only turns words into a plan
 * and checks the plan. Saving is the caller's job, after the owner
 * taps Apply. The module is pure and import-free so the test suite
 * runs it under node (the vexBuilds / drivetrain pattern). */

/* eslint-disable-next-line @typescript-eslint/no-explicit-any */
type Spec = any;

export type SizePart = 'wheels' | 'props' | 'body' | 'clearance';
type Dim = 'size' | 'long' | 'wide' | 'tall';

export interface PartChange {
  path: string;
  label: string;
  before: number;
  after: number;
}

export interface PartEditPlan {
  kind: 'size';
  part: SizePart;
  /* Plain name of the part, for the card ("the wheels"). */
  partLabel: string;
  /* The 3D model's part id to highlight (components/kit/takeapart). */
  viewId: string;
  phrase: string;
  changes: PartChange[];
}

export interface PartLookPlan {
  kind: 'look';
  viewId: string;
  partLabel: string;
  /* What the owner asked for, trimmed and capped. */
  description: string;
  phrase: string;
}

export interface PartEditCheck {
  /* Every spec field the edit changes; must equal the plan's paths. */
  changedPaths: string[];
  /* True when nothing outside the planned fields changed. */
  restKept: boolean;
  /* Things that would be physically wrong with the new size. */
  problems: string[];
  /* What else changes as a consequence, in plain words. */
  effects: string[];
}

const ALIASES: { part: SizePart; re: RegExp }[] = [
  { part: 'clearance', re: /\b(ground clearance|clearance|ride height)\b/ },
  { part: 'wheels', re: /\b(wheels?|tyres?|tires?)\b/ },
  { part: 'props', re: /\b(props?|propellers?|rotors?|blades?)\b/ },
  { part: 'body', re: /\b(body|chassis|deck|base ?plate|plate|frame|hull)\b/ },
];

