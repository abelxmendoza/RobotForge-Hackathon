// Shapes of the repo catalog data (catalog/*.json). Nested detail
// blobs keep index signatures — the JSON is the source of truth and
// the vanilla generator treats the same fields loosely.
export interface GateRunSummary {
  drive_error_pct?: number;
  heading_error_deg?: number;
  [key: string]: unknown;
}
export interface Robot {
  number: string | number;
  name: string;
  source: "my" | "sighted" | "photo" | "researched";
  slug?: string;
  class: string;
  subtype?: string;
  mobility_class?: string;
  description: string;
  image_url?: string;
  image_credit?: string;
  spec_file?: string;
  key_specs?: Record<string, unknown>;
  provenance?: Record<string, unknown>;
  gate_status?: { status: string; runs?: GateRunSummary[] } | string;
  [key: string]: unknown;
}
/* A REAL photograph (or, labelled, a manufacturer render) of a part,
 * web-gathered from the manufacturer's or an official supplier's
 * product page and hot-linked — never copied into the repo. This is
 * deliberately NOT the part's `image` field: those are AI
 * illustrations, and nothing may present them as photographs.
 * Gathered under the §8 discipline of the Forge Engine plan: the
 * record carries its receipt (source page + fetched-at) and its
 * trust state, and it exists only where the image was verified to
 * depict this exact part (or its recorded class exemplar, noted). */
export interface PartPhoto {
  url: string;
  source_page: string;
  credit: string;
  fetched_at: string;
  state: "web_gathered";
  kind: "photo" | "render";
  note?: string;
}

export interface Part {
  id: string;
  name: string;
  part_class: string;
  blurb?: string;
  used_for?: string;
  image?: string;
  photo?: PartPhoto | null;
  specs?: Record<string, unknown>;
  robot_types?: string[];
  notes?: string;
  source?: string;
  license?: string;
  [key: string]: unknown;
}
/* A build recipe in the parts catalogue: required catalogue parts
 * with quantities, plus optional part ids (catalog/parts.json
 * `templates`). The BOM wizard assembles from these verbatim. */
export interface PartTemplate {
  name: string;
  label: string;
  gate_pack?: string;
  required: Record<string, number>;
  optional: string[];
}
export interface GateReportRun {
  id: string;
  title: string;
  story?: string;
  doc?: Record<string, unknown>;
  traj?: unknown;
  [key: string]: unknown;
}
/* Take-apart parts kit (catalog/parts-kits.json, generated by
 * tools/build_parts_kits.py from src/robotforge/cad.py output).
 * kit is null when the generator defines no kit for the entry's
 * spec — the UI must say so, never invent parts. */
export interface KitParam {
  name: string;
  value_mm: number;
  source: string;
}
export interface KitPart {
  name: string;
  file: string;
  qty: number;
  does: string;
  dims: string;
  print_note: string;
  params: KitParam[];
}
export interface RobotKit {
  robot: string;
  spec_file?: string;
  kit: { estimated: boolean; parts: KitPart[] } | null;
  reason?: string;
}
/* In-browser physics checks (catalog/physics.json). status "urdf":
 * the entry's official model is a plain URDF at a pinned commit and
 * the checks run on it in the browser. status "none": the recorded
 * model is not a URDF (or not recorded at all) — the page shows the
 * reason instead of results. Nothing here is a verdict. */
export interface PhysicsEntry {
  status: "urdf" | "none";
  reason?: string;
  urdf_url?: string;
  packages?: Record<string, string>;
  source_label?: string;
  license?: string;
  model_note?: string;
  generated?: boolean;
  catalog_mass_kg?: number | null;
  catalog_mass_label?: string;
}
/* NVIDIA SimReady bench props (catalog/props/simready/props.json,
 * synced into src/data/simready-props.json). External CC BY 4.0
 * models used as bench dressing in the kit scene and as the Parts
 * palette's only 3D-model items. Mirrors the manifest's own fields
 * (components/kit/burger.ts carries the scene's fuller copy). */
export interface SimReadyPropEntry {
  id: string;
  name: string;
  file: string;
  source_package: string;
  source_url: string;
  attribution: string;
  size_m: [number, number, number];
  rotation_y_rad: number;
  [key: string]: unknown;
}
/* Robodex families (catalog/families.json, schema
 * robotforge-robodex-families/1): robots grouped by family, with
 * configuration variants told apart by a signature and individual
 * sightings filed under the variant they match. */
export interface DexSignature {
  manipulator: string;
  top_lidar: string;
  drivetrain: string;
  payloads: string[];
  [key: string]: unknown;
}
export interface DexSighting {
  id: string;
  identity: string;
  photo: string | null;
  sha256?: string | null;
  spotted_at?: string | null;
  where?: string | null;
  by?: string | null;
  /* The canonical families.json embeds the full Spotter dossier
   * object here; a plain path string is also accepted. */
  dossier?: string | Record<string, unknown> | null;
  [key: string]: unknown;
}
export interface DexVariant {
  label: string;
  signature: DexSignature;
  sightings: DexSighting[];
  [key: string]: unknown;
}
export interface Family {
  id: string;
  name: string;
  aliases: string[];
  catalog_dex_id: string | null;
  credit?: string;
  variants: DexVariant[];
  [key: string]: unknown;
}
