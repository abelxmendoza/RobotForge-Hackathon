"""Parts-kit data provenance + badge receipts.

catalog/parts-kits.json is generated by tools/build_parts_kits.py from
src/robotforge/cad.py. These tests pin the contract the Robodex UI
relies on:

- every Robodex entry has a parts-kit record (a real kit or an honest
  null with a reason — never a missing entry the UI could misread);
- a recorded kit matches what the CAD generator produces for that
  spec right now (spot-checked against the spec's own numbers);
- the Burger gate run recorded from the Torque VM run links a full
  report file that exists in the repo and whose numbers match the
  run summary in catalog/robots.json.
"""

import json
from pathlib import Path

REPO = Path(__file__).parent.parent


def _load(rel: str):
    return json.loads((REPO / rel).read_text(encoding="utf-8"))


def _slug(name: str) -> str:
    import re

    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def test_every_robot_has_a_kit_record():
    robots = _load("catalog/robots.json")["robots"]
    kits = _load("catalog/parts-kits.json")["kits"]
    for robot in robots:
        slug = _slug(robot["name"])
        assert slug in kits, f"{robot['name']} missing from parts-kits.json"
        entry = kits[slug]
        if entry["kit"] is None:
            assert entry.get("reason"), f"{slug}: null kit without a reason"
        else:
            assert entry["kit"]["parts"], f"{slug}: kit with no parts"


def test_burger_kit_params_come_from_its_spec():
    spec = _load("examples/turtlebot3-burger.json")
    kits = _load("catalog/parts-kits.json")["kits"]
    parts = {p["name"]: p for p in kits["turtlebot3-burger"]["kit"]["parts"]}
    wheel = {p["name"]: p["value_mm"] for p in parts["Wheel"]["params"]}
    assert wheel["wheel_diameter_mm"] == spec["wheel"]["diameter_m"] * 1000
    assert wheel["wheel_width_mm"] == spec["wheel"]["width_m"] * 1000
    plate = {p["name"]: p["value_mm"] for p in parts["Chassis plate"]["params"]}
    assert plate["chassis_length_mm"] == spec["length_m"] * 1000


def test_kitless_entries_are_the_wheelless_classes():
    kits = _load("catalog/parts-kits.json")["kits"]
    kitless = {s for s, e in kits.items() if e["kit"] is None}
    # The CAD kit generator builds wheeled ground-robot kits; the
    # aerial, legged, humanoid and arm entries have no wheel block.
    assert kitless == {
        "px4-x500", "crazyflie-2-1", "unitree-go2", "mini-pupper",
        "unitree-g1", "robotis-op3", "openmanipulator-x",
    }


def test_burger_torque_run_report_matches_summary():
    robots = _load("catalog/robots.json")["robots"]
    burger = next(r for r in robots if r["name"] == "TurtleBot3 Burger")
    run = burger["gate_status"]["runs"][-1]
    report_rel = run["report"]
    report = _load(report_rel)
    assert report["verdict"] == burger["gate_status"]["status"] == "PASS"
    checks = {c["name"]: c["error"] for c in report["checks"]}
    assert checks["drive_distance"] == run["drive_error_pct"]
    assert checks["turn_heading"] == run["heading_error_deg"]
    assert checks["odometry_distance"] == run["odometry_distance_error_pct"]
    assert checks["odometry_heading"] == run["odometry_heading_error_deg"]
